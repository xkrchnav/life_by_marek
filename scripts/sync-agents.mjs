import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (file) => readFileSync(join(root, file), "utf8");

const strip = (html) =>
  html
    .replace(/<br\s*\/?>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, " ")
    .trim();

const site = read("src/lib/site.ts");
const title = site.match(/\btitle:\s*"([^"]+)"/)?.[1];
const description = site.match(/\bdescription:\s*\n\s*"([^"]+)"/)?.[1];
const navigation = [...site.matchAll(/label:\s*"([^"]+)"/g)].map((match) => match[1]);

const heroH1 = strip(read("src/components/Hero.astro").match(/<h1[^>]*>([\s\S]*?)<\/h1>/)?.[1] ?? "");

const sectionFiles = {
  Benefits: "src/components/Benefits.astro",
  Steps: "src/components/Steps.astro",
  Tanita: "src/components/Tanita.astro",
  Story: "src/components/Story.astro",
  BlogTeaser: "src/components/BlogTeaser.astro",
  Faq: "src/components/Faq.astro",
  Cta: "src/components/Cta.astro",
};

const index = read("src/pages/index.astro");
const main = index.match(/<main[^>]*>([\s\S]*?)<\/main>/)?.[1] ?? "";
const order = [...main.matchAll(/<([A-Z][A-Za-z]+)(?:\s[^>]*)?\/>/g)].map((match) => match[1]);

const sections = [];
for (const name of order) {
  const file = sectionFiles[name];
  if (!file) continue;
  const heading = read(file).match(/<h2[^>]*>([\s\S]*?)<\/h2>/)?.[1];
  if (heading) sections.push(`  - ${name}: ${strip(heading)}`);
}

const blogDir = join(root, "src/content/blog");
const posts = readdirSync(blogDir)
  .filter((file) => file.endsWith(".mdx"))
  .map((file) => {
    const text = readFileSync(join(blogDir, file), "utf8");
    const frontmatter = text.match(/^---\r?\n([\s\S]*?)\r?\n---/)?.[1] ?? "";
    return {
      slug: file.replace(/\.mdx$/, ""),
      title: frontmatter.match(/^title:\s*"([^"]+)"/m)?.[1] ?? file,
      date: frontmatter.match(/^publishedAt:\s*(\d{4}-\d{2}-\d{2})/m)?.[1] ?? "",
      draft: /^draft:\s*true/m.test(frontmatter),
    };
  })
  .sort((a, b) => b.date.localeCompare(a.date));

const lines = [
  "_Auto-generated by `npm run agents:sync` from the source files. Do not edit by hand._",
  "",
  `- **Titulek:** ${title}`,
  `- **Popis:** ${description}`,
  `- **Navigace:** ${navigation.join(" · ")}`,
  `- **Hero H1:** „${heroH1}“`,
  "- **Sekce na úvodu (v pořadí):**",
  ...sections,
  `- **Články (${posts.length}):**`,
  ...posts.map(
    (post) =>
      `  - ${post.date} — ${post.title} (\`/clanky/${post.slug}/\`)${post.draft ? " — draft" : ""}`
  ),
];

const agentsPath = join(root, "AGENTS.md");
const agents = readFileSync(agentsPath, "utf8");
const eol = agents.includes("\r\n") ? "\r\n" : "\n";
const block = [
  "<!-- content-snapshot:start -->",
  ...lines,
  "<!-- content-snapshot:end -->",
].join(eol);

const pattern = /<!-- content-snapshot:start -->[\s\S]*?<!-- content-snapshot:end -->/;
if (!pattern.test(agents)) {
  console.error("AGENTS.md is missing the content-snapshot markers.");
  process.exit(1);
}

const updated = agents.replace(pattern, block);
const check = process.argv.includes("--check");

if (check) {
  if (updated !== agents) {
    console.error("AGENTS.md content snapshot is stale. Run `npm run agents:sync`.");
    process.exit(1);
  }
  console.log("AGENTS.md content snapshot is up to date.");
} else if (updated !== agents) {
  writeFileSync(agentsPath, updated, "utf8");
  console.log("AGENTS.md content snapshot updated.");
} else {
  console.log("AGENTS.md content snapshot already up to date.");
}
